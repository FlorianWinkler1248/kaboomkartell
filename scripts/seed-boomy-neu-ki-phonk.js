/**
 * Einmaliges Seed-Script: 4 Boomy-Suno-Tracks (NEU KI PHONK) in KBK-DB
 * einreihen — Status POOL, Pool-Mitgliedschaft "Phonk · AI".
 *
 * Ausfuehrung im KBK-Container:
 *   node scripts/seed-boomy-neu-ki-phonk.js   (auf dem Server, DATABASE_URL gesetzt)
 *
 * Idempotent: Slug ist unique, zweiter Run schlaegt fehl mit constraint
 * violation — das ist gewollt, kein Doppel-Seed.
 */

const Database = require('better-sqlite3');
const crypto = require('crypto');

const DB_PATH = '/app/data/kaboomkartell.db';
const POOL_ID = 'cmoebqq6z0000fnp1naziqy7w';   // Phonk · AI (Boomy-Source-Pool)
const BOOMY_ID = 'cmo3dgdh600018kofsob6684g';  // User Boomy
const COVER_URL = '/api/uploads/covers/boomy-neu-ki-phonk-source.jpg';

const TRACKS = [
  {
    title: 'Kill Switch',
    slug: 'kill-switch-c72a',
    file: 'boomy-kill-switch-c72aadee-afb347.mp3',
    size: 4807585,
  },
  {
    title: 'Midnight Grid',
    slug: 'midnight-grid-23eb',
    file: 'boomy-midnight-grid-23eb121a-b2c1f8.mp3',
    size: 5086262,
  },
  {
    title: 'Scalpel Saint',
    slug: 'scalpel-saint-e893',
    file: 'boomy-scalpel-saint-e893f7c6-9fc29e.mp3',
    size: 5126371,
  },
  {
    title: 'Shatter Queen',
    slug: 'shatter-queen-c202',
    file: 'boomy-shatter-queen-c2028af8-4dd6f1.mp3',
    size: 4777841,
  },
];

const cuid = () => 'c' + crypto.randomBytes(12).toString('hex');
const now = new Date().toISOString();

const db = new Database(DB_PATH);

// Spalten verifizieren — schlaegt frueh fehl wenn Schema nicht passt
const cols = db.prepare("PRAGMA table_info('tracks')").all().map((r) => r.name);
const required = ['id', 'title', 'slug', 'fileName', 'filePath', 'fileSize',
                  'duration', 'coverUrl', 'genre', 'bpm', 'status',
                  'aiDisclosure', 'aiSource', 'artistId', 'uploaderId',
                  'createdAt', 'updatedAt'];
for (const c of required) {
  if (!cols.includes(c)) {
    console.error(`ERROR: column '${c}' fehlt in tracks-Tabelle.`);
    process.exit(2);
  }
}

const insertTrack = db.prepare(`
  INSERT INTO tracks (
    id, title, slug, trackType, fileName, filePath, fileSize,
    duration, coverUrl, genre, bpm, description, status, playCount,
    sortOrder, aiDisclosure, aiSource, auraCount, susCount, totalVotes,
    susPercentage, artistId, uploaderId, createdAt, updatedAt
  ) VALUES (
    @id, @title, @slug, 'LOCAL', @file, @path, @size,
    0, @cover, 'phonk', 140, @desc, 'POOL', 0,
    0, 'ai_generated', 'suno', 0, 0, 0,
    0, @artist, @uploader, @now, @now
  )
`);

const insertPoolTrack = db.prepare(`
  INSERT INTO pool_tracks (id, poolId, trackId, addedAt)
  VALUES (?, ?, ?, ?)
`);

const tx = db.transaction((tracks) => {
  for (const t of tracks) {
    const trackId = cuid();
    const poolTrackId = cuid();
    insertTrack.run({
      id: trackId,
      title: t.title,
      slug: t.slug,
      file: t.file,
      path: '/app/uploads/tracks/' + t.file,
      size: t.size,
      cover: COVER_URL,
      desc: 'AI-generated by Boomy via Suno (NEU KI PHONK pack).',
      artist: BOOMY_ID,
      uploader: BOOMY_ID,
      now,
    });
    insertPoolTrack.run(poolTrackId, POOL_ID, trackId, now);
    console.log(`OK  ${t.title.padEnd(20)}  ${trackId.slice(0, 14)}...`);
  }
});

try {
  tx(TRACKS);
  console.log(`\n${TRACKS.length} Tracks in Pool 'Phonk · AI' eingereiht.`);
} catch (err) {
  console.error('SEED FAILED:', err.message);
  process.exit(1);
} finally {
  db.close();
}
